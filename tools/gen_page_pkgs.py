#!/usr/bin/env python3
"""Generate or verify the playground's package list.

docs/index.html draws its Packages pane (one tick box per package) from a
single line, `var PKGS = [...]`. That line is a function of packages/*.cz
and nothing else, so it is generated, never hand-edited:

    python3 tools/gen_page_pkgs.py           # rewrite the line in place
    python3 tools/gen_page_pkgs.py --check   # fail if it is out of date

--check is wired into `make test`: a package added without regenerating
(ts.cz and dsge.cz both shipped unlisted — LESSONS) is refused at the
suite. The verdict is the exit code."""
import glob, os, re, sys

PAGE = "docs/index.html"
LINE = re.compile(r"^(\s*)var PKGS = \[[^\]]*\];[^\n]*$", re.M)


def main():
    names = sorted(os.path.basename(p)[:-3] for p in glob.glob("packages/*.cz"))
    if not names:
        raise SystemExit("gen_page_pkgs: no packages/*.cz found (run from the repo root)")
    page = open(PAGE, encoding="utf-8").read()
    found = LINE.findall(page)
    if len(found) != 1:
        raise SystemExit(f"gen_page_pkgs: expected exactly one 'var PKGS = [...]' line in {PAGE}")
    want = LINE.sub(lambda m: m.group(1) + "var PKGS = [" + ",".join(f"'{n}'" for n in names) +
                    "];   /* GENERATED by tools/gen_page_pkgs.py from packages/*.cz */", page)
    if "--check" in sys.argv:
        if want != page:
            print(f"page packages: {PAGE} does not list packages/*.cz — run python3 tools/gen_page_pkgs.py")
            sys.exit(1)
        print(f"page packages: current ({len(names)} packages)")
        return
    open(PAGE, "w", encoding="utf-8").write(want)
    print(f"page packages: wrote {len(names)} packages to {PAGE}")


if __name__ == "__main__":
    main()
